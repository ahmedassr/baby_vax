"""Generates lib/app/core/service/growth/who_lms_data.dart from the WHO
Child Growth Standards z-score tables (.xlsx).

Usage (standard library only):
    python3 -I tool/who_growth/generate.py <dir with the 8 xlsx files> \
        > lib/app/core/service/growth/who_lms_data.dart
    dart format lib test

The xlsx files are downloaded from who.int (URLs and checksums in
docs/THIRD_PARTY.md). An .xlsx is a zip of XML, so no spreadsheet library is
needed. Only the Month, L, M and S columns are used; the published SD columns
are emitted separately as a test fixture with --fixture.
"""
import re
import sys
import zipfile
import xml.etree.ElementTree as ET

NS = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"

# (Dart name, [(file, first month, last month)], description)
TABLES = [
    ("weightForAgeBoys", [("wfa_boys.xlsx", 0, 60)], "Weight-for-age, boys, kg"),
    ("weightForAgeGirls", [("wfa_girls.xlsx", 0, 60)], "Weight-for-age, girls, kg"),
    # WHO convention: recumbent length below 24 months, standing height
    # from 24 months, so month 24 comes from the 2-5 years (height) table.
    ("lengthHeightForAgeBoys",
     [("lhfa_boys_0_2.xlsx", 0, 23), ("lhfa_boys_2_5.xlsx", 24, 60)],
     "Length/height-for-age, boys, cm (length 0-23 months, height 24-60)"),
    ("lengthHeightForAgeGirls",
     [("lhfa_girls_0_2.xlsx", 0, 23), ("lhfa_girls_2_5.xlsx", 24, 60)],
     "Length/height-for-age, girls, cm (length 0-23 months, height 24-60)"),
    ("headForAgeBoys", [("hcfa_boys.xlsx", 0, 60)],
     "Head circumference-for-age, boys, cm"),
    ("headForAgeGirls", [("hcfa_girls.xlsx", 0, 60)],
     "Head circumference-for-age, girls, cm"),
]


def rows(path):
    with zipfile.ZipFile(path) as z:
        try:
            ss = ET.fromstring(z.read("xl/sharedStrings.xml"))
            strings = ["".join(t.text or "" for t in si.iter(NS + "t"))
                       for si in ss.findall(NS + "si")]
        except KeyError:
            strings = []
        sheet = ET.fromstring(z.read("xl/worksheets/sheet1.xml"))
    out = []
    for row in sheet.iter(NS + "row"):
        cells = {}
        for c in row.findall(NS + "c"):
            col = re.match(r"[A-Z]+", c.get("r")).group(0)
            v = c.find(NS + "v")
            if v is None:
                continue
            cells[col] = strings[int(v.text)] if c.get("t") == "s" else v.text
        out.append(cells)
    header = {v.strip(): k for k, v in out[0].items()}
    return header, out[1:]


def num(s):
    return float(s)


def fmt(x):
    return repr(round(x, 6))


def load(directory, spec):
    """{month: (L, M, S, SD2neg, SD0, SD2)} for one table."""
    result = {}
    for name, first, last in spec:
        header, data = rows(f"{directory}/{name}")
        for r in data:
            month = int(num(r[header["Month"]]))
            if first <= month <= last:
                result[month] = tuple(num(r[header[k]]) for k in
                                      ("L", "M", "S", "SD2neg", "SD0", "SD2"))
    missing = [m for m in range(61) if m not in result]
    if missing:
        raise SystemExit(f"{spec}: missing months {missing}")
    return result


def main():
    directory = sys.argv[1]
    fixture = len(sys.argv) > 2 and sys.argv[2] == "--fixture"
    loaded = [(n, load(directory, spec), d) for n, spec, d in TABLES]
    if fixture:
        print("// GENERATED by tool/who_growth/generate.py --fixture. Do not edit.")
        print("//")
        print("// The WHO tables' own published -2 SD, median and +2 SD values")
        print("// (rounded to 0.1 by WHO), used to check the LMS maths.")
        print("// Source and licence: docs/THIRD_PARTY.md.")
        print()
        print("/// month -> (-2 SD, median, +2 SD), per table.")
        print("const Map<String, Map<int, (double, double, double)>> whoSdFixture = {")
        for n, t, _ in loaded:
            print(f"  '{n}': {{")
            for m in range(61):
                _, _, _, a, b, c = t[m]
                print(f"    {m}: ({fmt(a)}, {fmt(b)}, {fmt(c)}),")
            print("  },")
        print("};")
        return
    print("""// GENERATED by tool/who_growth/generate.py. Do not edit by hand.
//
// WHO Child Growth Standards: L, M and S parameters for each whole month
// of age from 0 to 60, for boys and girls, for three indicators.
//
// Source: World Health Organization, WHO Child Growth Standards, z-score
// tables (xlsx) for weight-for-age, length/height-for-age and
// head-circumference-for-age, birth to 5 years, downloaded from
// https://www.who.int/tools/child-growth-standards/standards on
// 11 and 13 November 2026 (byte-identical both times). File names,
// URLs and SHA-256 checksums: docs/THIRD_PARTY.md.
//
// Licence: CC BY-NC-SA 3.0 IGO (WHO's default licence for its
// publications). Attribution: "WHO Child Growth Standards. Geneva: World
// Health Organization; 2006. Licence: CC BY-NC-SA 3.0 IGO."
//
// Length/height: recumbent length for 0-23 months, standing height for
// 24-60 months, as WHO's own tables are split.

/// L, M and S for one month: the Box-Cox power, the median and the
/// coefficient of variation of the WHO reference distribution.
class WhoLms {
  /// Parameters for one month of age.
  const WhoLms(this.l, this.m, this.s);

  /// Box-Cox power.
  final double l;

  /// Median.
  final double m;

  /// Coefficient of variation.
  final double s;
}
""")
    for n, t, d in loaded:
        print(f"/// {d}. Index = age in whole months, 0-60.")
        print(f"const List<WhoLms> {n} = <WhoLms>[")
        for m in range(61):
            l, mm, s = t[m][:3]
            print(f"  WhoLms({fmt(l)}, {fmt(mm)}, {fmt(s)}),")
        print("];\n")


if __name__ == "__main__":
    main()
